#!/usr/bin/env python3
"""Regenerate font_data.cpp from TTF files (Poppins, SIL OFL 1.1).
usage: embed_fonts.py Poppins-Regular.ttf Poppins-Medium.ttf > font_data.cpp"""
import sys
names = ["kFontRegular", "kFontMedium"]
print("// Generated by tools/embed_fonts.py. Poppins, copyright The Poppins Project Authors, SIL Open Font License 1.1.")
print('#include "font_data.h"')
for n, path in zip(names, sys.argv[1:3]):
    data = open(path, "rb").read()
    print(f"const unsigned char {n}[] = {{")
    for i in range(0, len(data), 24):
        print("  " + ",".join(str(b) for b in data[i:i+24]) + ",")
    print("};")
    print(f"const unsigned int {n}Size = {len(data)};")
